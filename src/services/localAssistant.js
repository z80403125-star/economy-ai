export function getLocalEconomicsAnswer(question) {
  const normalized = question.toLowerCase().replace(/[?!,.;:]/g, " ").trim();

  for (const item of ECONOMICS_KNOWLEDGE) {
    if (item.terms.some((term) => normalized.includes(term))) {
      return item.answer;
    }
  }

  if (/^(привет|здравствуй|добрый день|доброе утро)/.test(normalized)) {
    return "Здравствуйте! Я локальный учебный помощник по экономике. Спросите о спросе, предложении, прибыли, выручке, инфляции, ВВП, налогах или другом экономическом понятии.";
  }

  if (/^(.{0,20})(что такое|что означает|как понять|объясни)/.test(normalized)) {
    return "Сформулируйте название экономического понятия точнее. Например: «Что такое спрос?», «Объясни прибыль», «Чем выручка отличается от прибыли?» или «Как работает рыночное равновесие?»";
  }

  return "По этому вопросу я могу дать краткое объяснение по базовой экономике. Уточните тему: спрос и предложение, цена и рыночное равновесие, выручка и прибыль, издержки, инфляция, ВВП, налоги или безработица.";
}
